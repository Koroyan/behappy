// Live AI check through the BeHappy server (costs a few cents of OpenAI usage).
//   node scripts/qa/ai-e2e.mjs --out ./qa-shots
// 1) Anulia: consent sheet → message → streamed reply
// 2) Journal: save entry without AI → optional reflection on request
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';

const args = process.argv.slice(2);
const out = path.resolve(args.includes('--out') ? args[args.indexOf('--out') + 1] : 'qa-shots');
const app = 'http://localhost:8081';
fs.mkdirSync(out, { recursive: true });

const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addInitScript(() => {
  try {
    localStorage.setItem('@behappy_onboarding_v2', 'done');
    localStorage.setItem('@behappy_language', 'en');
  } catch {}
});
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
let failed = false;

try {
  console.log('1. Anulia');
  await page.goto(`${app}/anulia`, { waitUntil: 'load', timeout: 90000 });
  await page.waitForSelector('[data-testid="composer-input"]', { timeout: 60000 });
  await page.fill('[data-testid="composer-input"]', 'Hi Anulia. Today I felt a bit tense at work. Who are you, briefly?');
  await page.click('[data-testid="composer-send"]');
  await page.waitForSelector('[data-testid="consent-sheet"]', { timeout: 20000 });
  await page.screenshot({ path: path.join(out, 'ai-1-consent.png') });
  await page.click('[data-testid="consent-agree"]');
  await page.waitForSelector('[data-testid="msg-ai"]', { timeout: 120000 });
  await page.waitForTimeout(1500);
  const reply = await page.locator('[data-testid="msg-ai"]').last().textContent();
  console.log('   reply:', reply?.replace(/\s+/g, ' ').slice(0, 300));
  await page.screenshot({ path: path.join(out, 'ai-2-reply.png') });
  if (!reply || reply.length < 10) failed = true;
  if (/Pijilo|licensed|psychologist/i.test(reply || '') && !/not a/i.test(reply || '')) console.log('   WARN: persona wording to review');

  console.log('2. Journal save without AI, then optional reflection');
  await page.goto(`${app}/journal/editor`, { waitUntil: 'load' });
  await page.waitForSelector('[data-testid="journal-body"]', { timeout: 60000 });
  await page.fill('[data-testid="journal-body"]', 'Today was long. I noticed I relax when I walk home slowly and listen to music.');
  await page.click('[data-testid="journal-save"]');
  await page.waitForSelector('[data-testid="journal-ask-reflection"]', { timeout: 30000 });
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('journal_entries') || '[]').length);
  console.log('   entries saved locally (before any AI call):', saved);
  if (saved < 1) failed = true;
  await page.click('[data-testid="journal-ask-reflection"]');
  await page.waitForFunction(() => {
    const el = document.querySelector('[data-testid="journal-reflection"]');
    // The AI-generated note appears only once a reflection has been saved.
    return el && /Generated by AI/i.test(el.textContent || '');
  }, null, { timeout: 120000 });
  const refl = await page.textContent('[data-testid="journal-reflection"]');
  console.log('   reflection:', refl?.replace(/\s+/g, ' ').slice(0, 300));
  await page.screenshot({ path: path.join(out, 'ai-3-reflection.png') });
} catch (e) {
  failed = true;
  console.error('FAIL', e.message);
  await page.screenshot({ path: path.join(out, 'ai-zz-error.png') }).catch(() => {});
} finally {
  if (errors.length) console.log('page errors:', errors.slice(0, 5));
  console.log(failed ? '\nFAIL' : '\nPASS');
  if (failed) process.exitCode = 1;
  await browser.close();
}
