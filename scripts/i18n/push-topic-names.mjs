// Writes server/notify/topicNames.mjs: each community room's name in every
// app language, taken from the app's own translations
// (i18n/locales/v3/<lang>.ts → community.topics.<id>.name), so a push says
// "Panic attacks" / "პანიკური შეტევები" exactly as the app does.
// Run after a topic or its translation changes: node scripts/i18n/push-topic-names.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(root, 'i18n', 'locales', 'v3');
const out = join(root, 'server', 'notify', 'topicNames.mjs');

const unquote = (q, s) => s.replace(new RegExp(`\\\\${q}`, 'g'), q).replace(/\\\\/g, '\\');

function topicsOf(source) {
  const start = source.search(/\n\s+topics: \{\n\s+panic: \{ name:/);
  if (start < 0) return null;
  const names = {};
  for (const line of source.slice(start).split('\n').slice(2)) {
    const m = /^\s+([a-z_]+): \{ name: (['"])((?:\\.|(?!\2).)*)\2/.exec(line);
    if (!m) break;
    names[m[1]] = unquote(m[2], m[3]);
  }
  return names;
}

const names = {};
for (const file of readdirSync(dir).filter((f) => /^[a-z]{2}\.ts$/.test(f)).sort()) {
  const t = topicsOf(readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n'));
  if (!t) throw new Error(`${file}: community.topics not found`);
  names[file.slice(0, 2)] = t;
}
const ids = Object.keys(names.en || {});
if (ids.length < 5) throw new Error('English topics not found');
for (const [lang, t] of Object.entries(names)) {
  const missing = ids.filter((id) => !t[id]);
  if (missing.length) throw new Error(`${lang}: missing ${missing.join(', ')}`);
}

const body = Object.entries(names)
  .map(([lang, t]) => `  ${lang}: {\n${ids.map((id) => `    ${id}: ${JSON.stringify(t[id])},`).join('\n')}\n  },`)
  .join('\n');
writeFileSync(
  out,
  `// Generated by scripts/i18n/push-topic-names.mjs from i18n/locales/v3 (community.topics.<id>.name).\n// Do not edit by hand: change the app's translation and run the script again.\n\nexport const TOPIC_NAMES = {\n${body}\n};\n`
);
console.log(`topicNames.mjs: ${ids.length} rooms × ${Object.keys(names).length} languages`);
